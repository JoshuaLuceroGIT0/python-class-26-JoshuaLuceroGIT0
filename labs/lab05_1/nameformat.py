def fullName(firstName, lastName):
    """Definition: A simple function that takes a firstName input and outputs the first and last name"""
    print(f"{firstName} {lastName}")
    print()

def lastNameFirst(firstName, lastName):
    """Definition: A simple function that takes a firstName input and outputs the last and first name with a comma in between."""
    print(f"{lastName}, {firstName}")
    print()

